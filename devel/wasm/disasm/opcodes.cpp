const OpInfo *find_op(u8 prefix, u32 sub)
{
    usize lo = 0, hi = sizeof OPS / sizeof OPS[0];
    while (lo < hi) {
        usize mid       = (lo + hi) / 2;
        const OpInfo &o = OPS[mid];
        if (o.prefix < prefix || (o.prefix == prefix && o.sub < sub))
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < sizeof OPS / sizeof OPS[0] && OPS[lo].prefix == prefix && OPS[lo].sub == sub)
        return &OPS[lo];
    return nullptr;
}
